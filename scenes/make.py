class Map:
    def __init__(self, w, h, fill=PLAIN):
        self.w, self.h = w, h
        self.t = [[fill] * w for _ in range(h)]

    def set(self, x, y, terrain):
        if 1 <= x <= self.w and 1 <= y <= self.h:
            self.t[y - 1][x - 1] = terrain

    def rect(self, x1, y1, x2, y2, terrain):
        for y in range(y1, y2 + 1):
            for x in range(x1, x2 + 1):
                self.set(x, y, terrain)

    def cells(self, cells, terrain):
        for x, y in cells:
            self.set(x, y, terrain)

    def path(self, points, terrain, bridge_over=None):
        """点を順に縦・横に結ぶ（道・川）。bridge_over の地形の上は橋にする"""
        for (x1, y1), (x2, y2) in zip(points, points[1:]):
            x, y = x1, y1
            while True:
                if bridge_over is not None and self.t[y - 1][x - 1] in bridge_over:
                    self.set(x, y, BRIDGE)
                else:
                    self.set(x, y, terrain)
                if (x, y) == (x2, y2):
                    break
                if x != x2:
                    x += 1 if x2 > x else -1
                else:
                    y += 1 if y2 > y else -1

    def text(self):
        # SRCAuthoring の MapDocument と同じ書き方: 1 行目 MapData、空行、幅,高さ、列（x）ごとに上から地形,画像
        lines = ['MapData', '', f'{self.w},{self.h}']
        for x in range(self.w):
            for y in range(self.h):
                lines.append(f'{self.t[y][x]},0')
        return '\r\n'.join(lines) + '\r\n'


def star(m, cx, cy, rx, ry, terrain, power=0.55):
    """上下左右に尖った４つの角を持つ星形（辺が内側へえぐれる）"""
    for y in range(1, m.h + 1):
        for x in range(1, m.w + 1):
            if (abs(x - cx) / rx) ** power + (abs(y - cy) / ry) ** power <= 1.0:
                m.set(x, y, terrain)


def U(unit, pilot, level, x, y, boss=None):
    """置くユニット。boss はボスランク（0〜5。強敵を強敵にする。省けばボスにしない）。ランクは省く（0）"""
    u = {'unit': unit, 'pilot': pilot, 'level': level, 'x': x, 'y': y}
    if boss is not None:
        u['bossRank'] = boss
    return u


def L(speaker, text):
    return {'speaker': speaker, 'text': text}


def spots(units):
    return [{'x': u['x'], 'y': u['y']} for u in units]


def scene(id, title, description, tags, titles, allies, enemies, opening, victory, defeat, extra_allies=(), extra_enemies=()):
    """作品の場面。おすすめの置く位置は、置くユニットの位置と、足すときの予備の位置（extra_*）"""
    return {
        'id': id, 'title': title, 'description': description, 'tags': tags,
        'allies': spots(allies) + list(extra_allies), 'enemies': spots(enemies) + list(extra_enemies),
        'titles': titles,
        'units': {'allies': allies, 'enemies': enemies},
        'talk': {'opening': opening, 'victory': victory, 'defeat': defeat},
    }


